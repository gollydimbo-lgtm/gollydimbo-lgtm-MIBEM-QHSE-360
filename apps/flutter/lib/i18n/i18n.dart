String t(String key, [Map<String, String>? params]) {
  final lang = appLang.value;
  var value = _dictionaries[lang]?[key] ?? _dictionaries['fr']?[key] ?? key;
  if (params != null) {
    params.forEach((k, v) => value = value.replaceAll('{{$k}}', v));
  }
  return value;
}
